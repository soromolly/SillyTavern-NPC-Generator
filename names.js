function pick(arr) {
    return arr[Math.floor(Math.random() * arr.length)];
}

function capitalize(str) {
    return str.charAt(0).toUpperCase() + str.slice(1);
}

export function generateName(race) {
    const key = (race || 'human').toLowerCase();
    const table = SYLLABLES[key] ?? SYLLABLES.human;

    const useMid = Math.random() < 0.55;
    const first = pick(table.start) + (useMid ? pick(table.mid) : '') + pick(table.end);
    const surnameSuffix = pick(SURNAME_PATTERNS[key] ?? SURNAME_PATTERNS.human);

    if (Math.random() < 0.35) {
        return capitalize(first);
    }

    const surnameBase = pick(table.start) + surnameSuffix;
    return `${capitalize(first)} ${capitalize(surnameBase)}`;
}
